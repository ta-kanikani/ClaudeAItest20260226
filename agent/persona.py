def test_persona() -> str:
    """
    瀬川 凛として200字の自己紹介を生成し、出力する。

    実行方法:
        python persona.py
    """
    import anthropic

    client = anthropic.Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"])
    test_prompt = "あなた自身の自己紹介を200字で書いてください"

    message = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=512,
        system=PERSONA_SYSTEM_PROMPT,
        messages=[{"role": "user", "content": test_prompt}],
    )

    result = message.content[0].text.strip()
    print("=" * 60)
    print(f"【ペルソナテスト】{PERSONA_NAME}（{PERSONA_NAME_KANA}）")
    print("=" * 60)
    print(result)
    print("=" * 60)
    print(f"文字数: {len(result)} 字")
    return result


